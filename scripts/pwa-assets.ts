/**
 * Generates PWA icons and iOS launch screens into public/pwa/ from the logo mark.
 * Run after changing the logo or brand colours: `npx tsx scripts/pwa-assets.ts`.
 * Also writes src/lib/pwa-splash.ts (the startupImage list for layout metadata).
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import sharp from "sharp";

const ROOT = join(import.meta.dirname, "..");
const OUT = join(ROOT, "public", "pwa");
const BLUE = "#0057b8";
const PAPER = "#f7f2e8";
const CORAL = "#e0573a";
/** Dark theme background: what the app paints first, so launch matches it. */
const NIGHT = "#0e1014";

/** The three books, in a 64-unit box. */
const books = `<rect x="14" y="16" width="9" height="34" rx="2" fill="${PAPER}"/><rect x="26" y="12" width="9" height="38" rx="2" fill="${PAPER}"/><rect x="38" y="20" width="9" height="30" rx="2" transform="rotate(-12 42 35)" fill="${CORAL}"/>`;

/** Full-bleed square (iOS and maskable icons get their shape from the OS). `scale` shrinks the books into the safe zone. */
const square = (scale: number) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" fill="${BLUE}"/><g transform="translate(${32 - 32 * scale} ${32 - 32 * scale}) scale(${scale})">${books}</g></svg>`;
/** Rounded tile for "any"-purpose icons shown as-is (desktop installs, Android without masks). */
const rounded = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" rx="14" fill="${BLUE}"/>${books}</svg>`;

async function png(svg: string, size: number, file: string) {
  await sharp(Buffer.from(svg))
    .resize(size, size)
    .png()
    .toFile(join(OUT, file));
}

/** iOS launch screens: portrait CSS size and pixel ratio of each device class. */
const DEVICES: [w: number, h: number, dpr: number][] = [
  [440, 956, 3], // Pro Max 16-17
  [420, 912, 3], // Air
  [402, 874, 3], // 16 Pro, 17, 17 Pro
  [430, 932, 3], // 14-15 Pro Max, Plus
  [393, 852, 3], // 14 Pro-16
  [428, 926, 3], // 12-13 Pro Max, 14 Plus
  [390, 844, 3], // 12-14, 16e, 17e
  [375, 812, 3], // X, XS, 11 Pro, minis
  [414, 896, 3], // XS Max, 11 Pro Max
  [414, 896, 2], // XR, 11
  [375, 667, 2], // SE, 8
  [744, 1133, 2], // iPad mini
  [820, 1180, 2], // iPad Air
  [834, 1194, 2], // iPad Pro 11
  [1024, 1366, 2], // iPad Pro 12.9
  [834, 1210, 2], // iPad Pro 11 (M4)
  [1032, 1376, 2], // iPad Pro 13 (M4), iPad Air 13
];
/** iPads launch in either orientation; phones' home screens are portrait. */
const isTablet = (w: number) => w >= 744;

async function splash(w: number, h: number, dpr: number, landscape = false) {
  const W = (landscape ? h : w) * dpr;
  const H = (landscape ? w : h) * dpr;
  const mark = 96 * dpr; // logo at 96pt, like a native launch screen
  const logo = await sharp(Buffer.from(rounded))
    .resize(mark, mark)
    .png()
    .toBuffer();
  const file = `splash-${W}x${H}.png`;
  await sharp({
    create: { width: W, height: H, channels: 3, background: NIGHT },
  })
    .composite([
      {
        input: logo,
        left: Math.round((W - mark) / 2),
        top: Math.round((H - mark) / 2),
      },
    ])
    .png({ compressionLevel: 9 })
    .toFile(join(OUT, file));
  return {
    url: `/pwa/${file}`,
    media: `(device-width: ${w}px) and (device-height: ${h}px) and (-webkit-device-pixel-ratio: ${dpr}) and (orientation: ${landscape ? "landscape" : "portrait"})`,
  };
}

async function main() {
  mkdirSync(OUT, { recursive: true });
  await png(rounded, 192, "icon-192.png");
  await png(rounded, 512, "icon-512.png");
  // Maskable: logo inside the central 80% safe zone.
  await png(square(0.72), 512, "maskable-512.png");
  await png(square(0.72), 192, "maskable-192.png");
  // iOS rounds and doesn't want transparency.
  await png(square(0.86), 180, "apple-touch-icon.png");

  const splashes = [];
  for (const [w, h, dpr] of DEVICES) {
    splashes.push(await splash(w, h, dpr));
    if (isTablet(w)) splashes.push(await splash(w, h, dpr, true));
  }
  writeFileSync(
    join(ROOT, "src", "lib", "pwa-splash.ts"),
    `// Generated by scripts/pwa-assets.ts. iOS launch screens (it ignores the manifest's background_color).\nexport const STARTUP_IMAGES = ${JSON.stringify(splashes, null, 2)};\n`,
  );
  console.log(`wrote ${5 + splashes.length} images to public/pwa`);
}

main();
